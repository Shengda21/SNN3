def interval(values):
    a = np.asarray(values, dtype=float)
    m = a.mean()
    h = t.ppf(.975, len(a)-1)*a.std(ddof=1)/np.sqrt(len(a)) if len(a)>1 else 0
    return m, m-h, m+h
def pm(values, scale=1, decimals=4):
    a = np.asarray(values)*scale
    return f'{a.mean():.{decimals}f} $\\pm$ {a.std(ddof=1):.{decimals}f}' if len(a)>1 else f'{a.mean():.{decimals}f}'
def table(name, label, caption, spec, header, rows, note):
    text = '\n'.join(['% Generated by scripts/build_revision_figures.py',
       '\\begin{table*}[t]', '\\centering', '\\caption{'+caption+'}',
       '\\label{'+label+'}', '\\begingroup\\fontsize{8}{10}\\selectfont',
       '\\setlength{\\tabcolsep}{4pt}', '\\begin{tabular}{'+spec+'}',
       '\\toprule', header + r' \\', '\\midrule',
       *[r + r' \\' for r in rows], '\\bottomrule', '\\end{tabular}',
       '\\par\\smallskip\\begin{minipage}{0.98\\textwidth}\\fontsize{8}{10}\\selectfont '+note+'\\end{minipage}',
       '\\endgroup', '\\end{table*}', ''])
    (T / name).write_text(text, encoding='utf-8')

